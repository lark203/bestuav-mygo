// writeProjectDocs 生成新项目自己的 README / CHANGELOG / 首次发布手册。
//
// 这三份都是从零写的，不从模板复制：bestuav-mygo 的同名文件写的是它自己的历史，
// 直接搬过去会让新项目一开篇就带着别人的变更记录与截图路径。
func writeProjectDocs(root string, o Options, kp keyPair) error {
	keyPath := kp.KeyPath
	if keyPath == "" {
		keyPath = privateKeyPathHint(o.ProjectName)
	}
	vars := strings.NewReplacer(
		"{{PROJECT}}", o.ProjectName,
		"{{BRAND}}", o.BrandName,
		"{{REPO}}", o.GitHubRepo,
		"{{IDENT}}", o.Identifier,
		"{{KEYPATH}}", keyPath,
	)

	if err := os.WriteFile(filepath.Join(root, "CHANGELOG.md"),
		[]byte(vars.Replace(strings.Join(changelogTmpl, "\n"))), 0o644); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(root, "README.md"),
		[]byte(vars.Replace(strings.Join(readmeTmpl, "\n"))), 0o644); err != nil {
		return err
	}
	docsDir := filepath.Join(root, "docs")
	if err := os.MkdirAll(docsDir, 0o755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(docsDir, "首次发布.md"),
		[]byte(vars.Replace(strings.Join(releaseManualTmpl, "\n"))), 0o644)
}

