// Package shell 是应用的「架构骨架」：左侧导航栏与右侧内容框（页头 + 分割线
// + 可滚动内容区）。
//
// 为什么单独成包
// --------------
// 这部分是**低频改动、但一改影响全局**的框架代码：所有页面都嵌在它里面，
// 间距、对齐、滚动行为稍动一点，整站观感就变。放进独立包后职责边界很清楚：
//
//   - shell：只负责「框」，不认识任何业务页面；
//   - kit  ：提供框内外复用的通用构件与间距规格；
//   - view ：业务页面 + 装配（把自己塞进 shell 的 Body 回调里）。
//
// 与业务解耦的方式是**回调 + 指针状态**，而不是 import 业务包：
// 侧栏把「当前页 id / 折叠态」以 *string / *bool 形式传进来，改动直接写回调用方
// 的字段，因此 shell 不需要知道 App 是什么类型（也就没有循环依赖）。
package shell

// 骨架几何常量（DIP）。
const (
	// HeaderHeight 页头高度。侧栏品牌头沿用同一高度，两条分割线才能落在同一
	// 水平线上（见 content.go 的说明）。
	HeaderHeight = 52

	// DividerSlot 分割线槽位高度：常态画 1px 浅线，轻量任务执行时同槽位画
	// 进度条，槽位高度固定 → 进度条出现/消失都不会让下方内容跳动。
	DividerSlot = 3

	// ExpandedWidth 侧栏展开宽度；CollapsedWidth 收缩后（图标栏/rail）宽度。
	ExpandedWidth  = 220
	CollapsedWidth = 64

	// 侧栏图标规格。
	NavIconSize   = 16 // 菜单项图标
	BrandIconSize = 20 // 品牌标志（居中后仍与菜单图标中心对齐）
	ChevronSize   = 14 // 分组标题右侧箭头

	// scrollbarHideInset 把某个滚动容器的滚动条推到可视区外（= 隐藏）。
	//
	// mygo 的滚动条颜色来自全局 Theme，且没有「单个容器隐藏」的开关；但滚动条
	// 的绘制位置是可调的（ScrollbarInsets，顺序为 上/右/下/左）。给右侧一个远大于
	// 容器宽度 的内缩值，竖直滚动条 X 坐标就会变成负数、落到窗口左边界之外，
	// 从而不可见也不可点。侧栏用它隐藏自己的滚动条，内容区则保留正常滚动条。
	scrollbarHideInset = 400
)
